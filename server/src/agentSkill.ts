/** 给飞书智能体 / 豆包 / Cursor 粘贴的说明书。钥匙只出现这一次。 */
export function buildAgentSkillMarkdown(opts: { base: string; token: string; userName: string }): string {
  const { base, token, userName } = opts
  return [
    '---',
    'name: kb-web',
    'description: 工厂知识库。提问先检索再回答，有出处；没有资料就直说，不要编。口述经验可入库待确认。',
    '---',
    '',
    '# 工厂知识库',
    '',
    `你在帮网页账号「${userName}」查内部规程。你负责说话；知识由 kb-web 提供。`,
    '检索只返回片段和出处，**答案由你写**，正文里保留 `[1]` `[2]`。不要编造。',
    '',
    '> 本文件含访问钥匙，等同登录。别外传、别提交到 git、别贴进公开群。',
    '',
    '## 连接',
    '',
    `- 地址：\`${base}\``,
    `- 认证：\`Authorization: Bearer ${token}\``,
    '',
    '## 提问时检索',
    '',
    '用户问设备、规程、故障时，先调这个接口，再根据返回写回答：',
    '',
    '```',
    `POST ${base}/api/agent/search`,
    `Authorization: Bearer ${token}`,
    'Content-Type: application/json',
    '',
    '{"query":"<用户问题>","limit":5}',
    '```',
    '',
    '返回只有 `hits`（片段 + `[1]` 出处）或 `noEvidence`。没有 `answer`。',
    '- 有 hits：只根据片段写，正文保留出处标记',
    '- 有 noEvidence：照它回答「没有资料」，不要推测',
    '- 不要带 channel / external_id，钥匙已经对应这个人',
    '',
    '## 提交经验 / 日报',
    '',
    '用户口述了经验、踩坑、日终总结时（原文照录，不要自己改写成要点）：',
    '',
    '```',
    `POST ${base}/api/agent/capture`,
    `Authorization: Bearer ${token}`,
    'Content-Type: application/json',
    '',
    '{"title":"<短标题>","content":"<正文>","kind":"经验","field":"electrical"}',
    '```',
    '',
    '- kind：经验 / 日报；field：electrical / dispatch / mechanical',
    '- 返回 `status: pending`：告诉用户「管理员确认后才进正式库」',
    '- 同标题重复会 `duplicate: true`，不要连刷',
    '',
    '## 必须遵守',
    '',
    '1. 权限由服务端按这个网页账号过滤，不要尝试绕过',
    '2. 没有命中就说没有资料',
    '3. 钥匙泄露：让用户回知识库网页重新下载 Skill，旧文件立刻作废',
  ].join('\n')
}
